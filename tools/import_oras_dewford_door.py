#!/usr/bin/env python3
"""Bake genuine Dewford BM0034 door poses from a user-supplied ORAS source."""
import argparse, hashlib, json, math, sys
from pathlib import Path
from import_oras_center_doors import mul, sample
from import_oras_grass import lua
from oras_scenery_source import decoder

def convert(model, animation, textures, decoder_path, nitrogen_path, output):
    load, load_textures, png = decoder(decoder_path)
    raw = model.read_bytes(); m = load(raw)[0]
    assert m.name == 't103_bm_door01' and len(m.bones) == 5
    sys.path.insert(0, str(nitrogen_path))
    from nitrogen.platforms.ctr.bch import open_bch
    independent = open_bch(raw).models[0]
    worlds = []; errors = {}
    for i, b in enumerate(independent.skeleton):
        assert b.name == m.bones[i].name and all(abs(x) < 1e-8 for x in b.rotation)
        t = [[b.scale[r] if r == c else b.translation[r] if c == 3 else 0 for c in range(4)] for r in range(3)] + [[0, 0, 0, 1]]
        if b.parent >= 0: t = mul(worlds[b.parent], t)
        worlds.append(t)
        check = mul(t, [b.inverse_bind[k:k+4] for k in range(0, 16, 4)])
        errors[b.name] = max(abs(check[r][c] - (r == c)) for r in range(4) for c in range(4))
    assert max(errors[m.bones[i].name] for i in (0, 1)) < 1e-5
    from ctr.formats.bch.header import read_header, relocate
    from ctr.binstream import BinStream
    from ctr.formats.bch.contents import read_contents
    from ctr.formats.bch.animation import read_animations
    a = animation.read_bytes(); h = read_header(BinStream(a)); rel = relocate(a, h)
    motions = read_animations(rel, read_contents(rel, h), h.backward)
    assert len(motions) == 1 and motions[0].frame_count == 6 and not motions[0].looping
    track = next(b for b in motions[0].bones if b.name == 'anim_door')
    assert not track.is_axis_angle and not any(t.keys for t in track.scale + track.translation)
    assert all(abs(k.value) < 1e-8 for axis in (0, 2) for k in track.rotation[axis].keys)
    sub = next(s for s in m.submeshes if s.material == 'pasted__muro_house_muro_door')
    assert len(sub.positions) == 34 and len(sub.triangles) == 18 and sub.uv0
    assert all(b == [1] for b in sub.bones) and all(w == [1.] for w in sub.weights)
    assert all(abs(color[3] - 1) < 1e-8 for color in sub.colors)
    angles = [sample(track.rotation[1].keys, frame) for frame in (0., 2.5, 5.)]
    assert abs(angles[0]) < 1e-8 and abs(angles[-1] + math.radians(80)) < 1e-6
    poses = []
    for angle in angles:
        c, s = math.cos(angle), math.sin(angle)
        rotation = [[c, 0, s, 0], [0, 1, 0, 0], [-s, 0, c, 0], [0, 0, 0, 1]]
        matrix = mul(worlds[1], rotation)
        pose = []
        for p, uv in zip(sub.positions, sub.uv0):
            point = [sum(matrix[r][k] * (p[k] if k < 3 else 1) for k in range(4)) for r in range(3)]
            pose.append(point + [uv[0], 1 - uv[1], 1.])
        poses.append(pose)
    closed = poses[0]; bounds = [min(p[k] for p in closed) for k in range(3)] + [max(p[k] for p in closed) for k in range(3)]
    span = bounds[3] - bounds[0]; origin = [(bounds[0] + bounds[3]) / 2, bounds[1], bounds[5]]
    for pose in poses:
        for p in pose:
            for k in range(3): p[k] = (p[k] - origin[k]) / span
    folder = output / 'assets/scenery/oras-dewford-door'; folder.mkdir(parents=True, exist_ok=True)
    texture = next(t for t in load_textures(textures.read_bytes()) if t.name == 'muro_door')
    content = png(texture.rgba, texture.width, texture.height); (folder / 'muro_door.png').write_bytes(content)
    part = dict(name='source_hinged_door', vertices=poses[0], indices=[i+1 for tri in sub.triangles for i in tri],
                texture='assets/scenery/oras-dewford-door/muro_door.png', opacity=1., alphaMode='cutout', role='source_dewford_door')
    data = dict(id='oras_dewford_hinged_door', parts=[part], poses=poses, height=(bounds[4]-bounds[1])/span,
                sourceSpan=span, sourceBounds=bounds, sourceOrigin=origin, sourceAngles=angles)
    (output / 'lib/ImportedDewfordDoorData.lua').write_text('-- Genuine ORAS BM0034 hinged door; generated by tools/import_oras_dewford_door.py.\nreturn '+lua(data)+'\n')
    report = dict(source='User-supplied Pokemon Alpha Sapphire RomFS', modelArchive='a/0/2/3 BM0034 slot0',
        animationArchive='a/0/2/3 BM0034 slot1', textureArchive='a/0/1/4 AD0010 slot1', modelName=m.name,
        originalGameArt='Nintendo / Creatures / GAME FREAK', triangles=18, sourceBoundsYUp=bounds,
        movingBone='anim_door', movingBoneInverseBindMaximumError=max(errors[m.bones[i].name] for i in (0, 1)),
        sha256=dict(modelBch=hashlib.sha256(raw).hexdigest(), animationBch=hashlib.sha256(a).hexdigest(),
                    textureBch=hashlib.sha256(textures.read_bytes()).hexdigest(), png=hashlib.sha256(content).hexdigest()),
        texture=dict(name='muro_door', size=[texture.width, texture.height], rgbaSha256=hashlib.sha256(texture.rgba).hexdigest()),
        sourceAnimation=dict(frames=6, looping=False, samples=[0, 2.5, 5], yRotationRadians=angles),
        sourceVertexColors=sorted(set(sub.colors)),
        processing='All18 original physical door triangles and UVs retained, with source V-origin conversion once. Rigid bind independently checked with Nitrogen inverse matrices; source local Y-rotation sampled through original Hermite track. Source PNG paint is unchanged; baked vertex tints are omitted per user clean-lighting preference. The separate24-triangle untextured floor-light effect is omitted. Uniform fit inside the original source house doorway; native engine owns frame, collision, warp, sound and timing.')
    (folder / 'provenance.json').write_text(json.dumps(report, indent=2)+'\n')
    return data, report

if __name__ == '__main__':
    p = argparse.ArgumentParser(description=__doc__)
    for name in ['model', 'animation', 'textures', 'decoder', 'nitrogen', 'output_root']:
        p.add_argument('--'+name.replace('_', '-'), type=Path, required=True)
    a = p.parse_args(); _, report = convert(a.model, a.animation, a.textures, a.decoder, a.nitrogen, a.output_root)
    print(json.dumps(dict(triangles=report['triangles'], bindError=report['movingBoneInverseBindMaximumError'])))
