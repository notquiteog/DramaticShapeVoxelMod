def close_tv():
    vertices=[]
    uv=[55.5/64,55.5/64]
    def triangle(a,b,c):
        for p in (a,b,c):vertices.append(list(p)+uv+[1])
    def polygon(points):
        # Ear-clip the concave stand footprint without filling beyond its rim.
        axis=1 if all(abs(p[1]-points[0][1])<1e-6 for p in points) else 2
        xy=lambda p:(p[0],p[2] if axis==1 else p[1])
        cross=lambda a,b,c:(b[0]-a[0])*(c[1]-a[1])-(b[1]-a[1])*(c[0]-a[0])
        area=sum(xy(points[i])[0]*xy(points[(i+1)%len(points)])[1]-xy(points[(i+1)%len(points)])[0]*xy(points[i])[1] for i in range(len(points)))
        sign=1 if area>0 else -1
        ids=list(range(len(points)))
        while len(ids)>3:
            for i in range(len(ids)):
                a,b,c=ids[i-1],ids[i],ids[(i+1)%len(ids)];aa,bb,cc=map(xy,(points[a],points[b],points[c]))
                if cross(aa,bb,cc)*sign<=1e-10:continue
                def inside(p):
                    return all(cross(u,v,p)*sign>=-1e-10 for u,v in ((aa,bb),(bb,cc),(cc,aa)))
                if any(inside(xy(points[j])) for j in ids if j not in (a,b,c)):continue
                triangle(points[a],points[b],points[c]);ids.pop(i);break
            else:raise ValueError('TV closure cannot triangulate source rim')
        triangle(*(points[i]for i in ids))
    polygon([[-1.857898,.41271,-.09711],[1.825541,.41271,-.09711],
             [1.825541,2.682863,-.09711],[-1.857898,2.682863,-.09711]])
    polygon([[-1.857898,.41271,-.09711],[1.825541,.41271,-.09711],
             [1.825541,.41271,.09711],[-1.857898,.41271,.09711]])
    foot=[[-.85524,0,-.07029],[-1.23623,0,.19559],[-1.11994,0,.31519],
          [-.65455,0,.13042],[-.00063,0,.09711],[.65329,0,.13042],
          [1.11869,0,.31519],[1.23498,0,.19559],[.85399,0,-.07029],[-.00063,0,-.291325]]
    polygon(foot)
    polygon([[-.3929,.15913,-.18979],[.39164,.15913,-.18979],
             [.39164,.46126,-.18979],[-.3929,.46126,-.18979]])
    for y in (.15913,.46126):
        polygon([[-.3929,y,-.18979],[-.25852,y,.04839],[-.00063,y,.07848],
                 [.25725,y,.04839],[.39164,y,-.18979]])
    return {'name':'authored_rear_and_stand_closure','material':'authored_case_swatch',
            'texture':'terebi0.png','diffuse':[.64,.64,.64],'opacity':1,
            'vertices':vertices,'wrapS':'repeat','wrapT':'repeat','authored':True}


def convert(path, output):
    raw_archive=path.read_bytes()
    with zipfile.ZipFile(io.BytesIO(raw_archive)) as z:
        if len(z.infolist())>32 or sum(i.file_size for i in z.infolist())>8388608:
            raise ValueError('TV archive exceeds budget')
        names={PurePosixPath(safe_path(n)).name:n for n in z.namelist() if not n.endswith('/')}
        raw=z.read('TV/terebi.obj')
        source,fixes=obj(raw,materials(z.read('TV/terebi.mtl')),names)
        # The export includes an alternate animated screen at precisely the
        # same plane and a planar authored shadow. Select the original off
        # screen once; the renderer owns world shadows and source glow is an
        # unused effect for this unpowered presentation.
        parts=[p for p in source if p['material']=='terebi0.png']
        if len(parts)!=2:raise ValueError('Unexpected TV source material split')
        # Original exported off-screen touches the neighboring green unused
        # atlas region at its bottom edge. Keep the original screen pixels.
        for v in parts[0]['vertices']:v[4]=min(v[4],19.5/64)
        parts.append(close_tv())
        fixes.extend(['Off-screen bottom UV clamped to original grayscale row19 texel center, excluding adjacent unused green atlas pixels.',
                      'Separately authored rear case and stand underside caps follow original open rims; source geometry unchanged.'])
        meta=normalize(parts)
        folder=output/'assets/scenery/interiors/oras_tv';folder.mkdir(parents=True,exist_ok=True)
        textures={}
        for p in parts:
            name=PurePosixPath(p['texture']).name;content=z.read(names[name]);im=Image.open(io.BytesIO(content));im.verify()
            (folder/name).write_bytes(content)
            textures[name]={'sha256':hashlib.sha256(content).hexdigest(),'bytes':len(content)}
            p['texture']='assets/scenery/interiors/oras_tv/'+name
            p['role']='structure';p['alphaMode']='cutout'
        data={'oras_home_tv':{'parts':parts,'anchors':{},'revision':1}}
        (output/'lib/ImportedInteriorTVData.lua').write_text('-- Generated by tools/import_interior_tv.py; attribution is beside the selected texture.\nreturn '+lua(data)+'\n')
        report={'asset':294979,'title':'TV','game':'Pokémon Omega Ruby / Alpha Sapphire','author':'Hallow','submitted':'2015-11-15',
                'sourcePage':'https://models.spriters-resource.com/3ds/pokemonomegarubyalphasapphire/asset/294979/',
                'originalGameArt':'Nintendo / Creatures / GAME FREAK',
                'archiveSha256':hashlib.sha256(raw_archive).hexdigest(),'sourceModelSha256':hashlib.sha256(raw).hexdigest(),
                'selection':'Original static body plus original terebi0 off-screen. Alternate coplanar animated screen/glow and planar ground shadow are not selected.',
                'textures':textures,'repairs':fixes,**meta,
                'parts':[{'name':p['name'],'material':p['material'],'triangles':p['triangles'],'authored':bool(p.get('authored'))}for p in parts]}
        (folder/'provenance.json').write_text(json.dumps(report,indent=2,ensure_ascii=False)+'\n')
        return data

