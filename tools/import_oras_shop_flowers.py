#!/usr/bin/env python3
"""Retain three original pink Pretty Petal blossoms that fit their native planter."""
import argparse,copy,hashlib,io,json,zipfile
from pathlib import Path
from import_oras_grass import lua
from import_route104_shop import extract,SOURCE
from import_route104_tree import URL,bounds
from import_scenery_models import normalize

IDS=(5,6,9)
MODEL='oras_route104_pretty_petal_pink_flowers'
def convert(archive_path,output_root):
    raw=Path(archive_path).read_bytes();root=Path(output_root)
    with zipfile.ZipFile(io.BytesIO(raw))as archive:
        dae=archive.read(SOURCE);architecture,flora=extract(dae,True)
        # Reuse the exact existing shop normalization, including its authored
        # completion. No flower fit or UV changes occur during this transform.
        from import_route104_shop import complete
        added,_=complete(architecture);architecture.extend(added)
        meta=normalize(architecture);origin,span=meta['sourceOrigin'],meta['sourceUnitSpan']
        components=[]
        for index in IDS:
            original=flora[index-1];b=bounds(original)
            assert len(original)==24 and b[0]>133.21 and b[3]<176.84 and b[2]>163.81 and b[5]<175.79,'flower leaves original planter'
            rows=[];colors=[];indices=[];seen={}
            for v in original:
                row=[(v[k]-origin[k])/span for k in range(3)]+v[3:]
                key=tuple(row)
                if key not in seen:seen[key]=len(rows)+1;rows.append(row[:6]);colors.append(row[6:])
                indices.append(seen[key])
            components.append({'sourceComponent':index,'identity':'pink_flower_yellow_center','vertices':rows,'colors':colors,'indices':indices,'sourceBounds':b})
        data={MODEL:{'components':components,'excludedHd2dCards':{i:True for i in IDS},'sourcePlanterBounds':[133.21,163.81,176.84,175.79],
                     'planterBounds':[(v-origin[k])/span for v,k in [(133.21,0),(163.81,2),(176.84,0),(175.79,2)]],
                     'texture':'assets/scenery/oras-route104-shop/r104_dif03.png'}}
        (root/'lib/ImportedHoennFlowerData.lua').write_text('-- Original ORAS pink blossom surfaces; generated by tools/import_oras_shop_flowers.py.\nreturn '+lua(data)+'\n')
        report={'asset':364272,'sourcePage':URL,'game':'Pokemon Omega Ruby / Alpha Sapphire','sourceFile':SOURCE,
                'archiveSha256':hashlib.sha256(raw).hexdigest(),'sourceSha256':hashlib.sha256(dae).hexdigest(),
                'sourceMaterial':'_2_0-mesh / r104_dif03.png','sourceComponents':list(IDS),'sourceTriangles':24,
                'identity':'Three pink blossoms with yellow centers in the existing front masonry planter.',
                'geometry':'Original authored bent flower surfaces. These are source textured surfaces, not newly sculpted closed petals. All original XYZ relationships, UVs, shade and RGBA are retained; only the existing shop uniform normalization/placement is applied.',
                'textureSha256':hashlib.sha256(archive.read('r104_dif03.png')).hexdigest(),
                'normalization':meta,'sourcePlanterBounds':[133.21,163.81,176.84,175.79],
                'default':'All19 source flower/leaf components remain current HD2D cards.',
                'modern':'Only source components5/6/9 use their authored geometry. The other16 stay current HD2D. Each selected component remains within both the original planter and the native96x48blocked body; no clamping, stretching or relocation.',
                'voxel':'An optional native-sprite voxel provider can supply this family. Without that provider, return native-source-unavailable so the Hoenn caller restores the entire native-art Civic building. Do not call ORAS-textured cards native GBA voxel art.',
                'limits':'No standalone route flowerbed, other flower color/family, other map, or BDSP model is claimed.'}
        folder=root/'assets/scenery/oras-route104-shop';(folder/'flowers-provenance.json').write_text(json.dumps(report,indent=2)+'\n')
        return data,report
if __name__=='__main__':
    parser=argparse.ArgumentParser();parser.add_argument('archive');parser.add_argument('--output-root',default='.');args=parser.parse_args();_,report=convert(args.archive,args.output_root);print(json.dumps({'components':report['sourceComponents'],'triangles':report['sourceTriangles']}))
