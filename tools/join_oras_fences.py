#!/usr/bin/env python3
"""Join reviewed native fence runs with one owner for each coplanar surface.

Uses only the committed source modules and native-family layout. Original UVs
are interpolated across cut triangles; source textures are never repainted.
"""
import copy, json, math, subprocess
from pathlib import Path
from import_oras_grass import lua
from oras_rear_closure import _subtract, _area


def plane(tri):
 a,b,c=tri;u=[b[k]-a[k]for k in range(3)];v=[c[k]-a[k]for k in range(3)]
 n=[u[1]*v[2]-u[2]*v[1],u[2]*v[0]-u[0]*v[2],u[0]*v[1]-u[1]*v[0]]
 length=math.sqrt(sum(x*x for x in n))
 if length<1e-10:return
 n=[x/length for x in n];axis=max(range(3),key=lambda k:abs(n[k]));sign=1 if n[axis]>0 else -1
 return tuple(round(x*sign,6)for x in n)+(round(sum(n[k]*a[k]for k in range(3))*sign,6),),axis,sign


def clean(parts):
 records=[];groups={}
 for pi,p in enumerate(parts):
  for i in range(0,len(p['indices']),3):
   tri=[p['vertices'][k-1]for k in p['indices'][i:i+3]];q=plane(tri)
   if not q:continue
   key,axis,sign=q;axes=[k for k in range(3)if k!=axis];poly=[[v[k]for k in axes]for v in tri]
   r=dict(tri=tri,poly=poly,axes=axes,pi=pi,sign=sign,number=len(records),key=key)
   r['bounds']=[min(v[k]for v in poly)for k in range(2)]+[max(v[k]for v in poly)for k in range(2)]
   records.append(r);groups.setdefault(key,[]).append(r)
 out=[dict(p,vertices=[],indices=[])for p in parts]
 for r in records:
  polys=[r['poly']];b=r['bounds']
  for other in groups[r['key']]:
   if other is r or other['sign']==r['sign']and other['number']>r['number']:continue
   c=other['bounds']
   if b[0]>=c[2]-1e-8 or b[2]<=c[0]+1e-8 or b[1]>=c[3]-1e-8 or b[3]<=c[1]+1e-8:continue
   polys=[q for p in polys for q in _subtract(p,other['poly'])]
   if not polys:break
  a,b,c=r['poly'];den=(b[1]-c[1])*(a[0]-c[0])+(c[0]-b[0])*(a[1]-c[1])
  def vertex(p):
   w0=((b[1]-c[1])*(p[0]-c[0])+(c[0]-b[0])*(p[1]-c[1]))/den
   w1=((c[1]-a[1])*(p[0]-c[0])+(a[0]-c[0])*(p[1]-c[1]))/den;weights=[w0,w1,1-w0-w1]
   return [sum(t[k]*w for t,w in zip(r['tri'],weights))for k in range(6)]
  p=out[r['pi']]
  for poly in polys:
   if abs(_area(poly))<1e-8:continue
   vs=[vertex(q)for q in poly]
   for i in range(1,len(vs)-1):
    tri=[vs[0],vs[i],vs[i+1]]
    if not plane(tri):continue
    start=len(p['vertices']);p['vertices'].extend(tri);p['indices'].extend([start+1,start+2,start+3])
 return [p for p in out if p['indices']]


def rural_model(data, profile):
 original=data['parts'][0]
 triangles=[[original['vertices'][k-1]for k in original['indices'][i:i+3]]for i in range(0,len(original['indices']),3)]
 assert len(triangles)==70, 'reviewed source primitive topology changed'
 posts=[[],[]]
 for tri in triangles[:34]:
  n=0 if max(v[0]for v in tri)<8 else 1
  assert all((v[0]<8)==(n==0)for v in tri)
  posts[n].append(tri)
 assert [len(p)for p in posts]==[16,18]
 template=triangles[34:46]
 assert min(v[0]for t in template for v in t)==0 and max(v[0]for t in template for v in t)==2.75
 out=[]
 for n,(x,z,rotation)in enumerate(profile['posts']):
  source=n%2;cx=(4,12)[source]
  for tri in posts[source]:
   transformed=[]
   for vertex in tri:
    v=vertex.copy();vx,vz=v[0]-cx,v[2]-8
    if rotation:vx,vz=-vz,vx
    v[0],v[2]=x+vx,z+vz;transformed.append(v)
   out.append(transformed)
 for x0,z0,x1,z1 in profile['runs']:
  vertical=x0==x1
  assert vertical != (z0==z1), 'source rail must be axis aligned'
  lo,hi=(z0,z1)if vertical else(x0,x1)
  spans=[(lo,hi)]
  for x,z,rotation in profile['posts']:
   if abs((x if vertical else z)-(x0 if vertical else z0))>1e-7:continue
   center=z if vertical else x
   half=1.25 if rotation==int(vertical)else 1.0
   spans=[q for a,b in spans for q in ((a,min(b,center-half)),(max(a,center+half),b))if q[1]-q[0]>1e-7]
  for a,b in spans:
   for tri in template:
    transformed=[]
    for vertex in tri:
     v=vertex.copy();axis=a+v[0]/2.75*(b-a);cross=v[2]-8
     v[0],v[2]=(x0-cross,axis)if vertical else(axis,z0+cross)
     transformed.append(v)
    out.append(transformed)
 part=copy.deepcopy(original);part['name']='source_closed_posts_and_rail_union'
 part['vertices']=[v for tri in out for v in tri];part['indices']=list(range(1,len(part['vertices'])+1))
 return dict(parts=clean([part]),anchors={'center':[8,0,8]})


def precise_lua(value):
 if isinstance(value,dict):return '{'+','.join('['+precise_lua(k)+']='+precise_lua(v)for k,v in value.items())+'}'
 if isinstance(value,list):return '{'+','.join(precise_lua(v)for v in value)+'}'
 if isinstance(value,(int,float))and not isinstance(value,bool):return format(value,'.15g')
 return lua(value)


def write_models(path, models, precision=7):
 # Independent factory functions keep each LuaJIT constant pool bounded;
 # identical families share one immutable geometry definition.
 chunks=['-- Generated by tools/join_oras_fences.py; exact native rail axes.']
 aliases={};unique={}
 for name,model in sorted(models.items()):
  for p in model['parts']:
   p['vertices']=[[round(value,precision)+0.0 for value in v]for v in p['vertices']]
  key=json.dumps(model,sort_keys=True)
  if key not in unique:
   variable='m'+str(len(unique)+1);unique[key]=variable
   chunks.append('local '+variable+'=(function()return '+(precise_lua(model)if precision>7 else lua(model))+' end)()')
  aliases[name]=unique[key]
 chunks.append('return {'+','.join('["'+name+'"]='+value for name,value in aliases.items())+'}')
 path.write_text('\n'.join(chunks)+'\n')


def generate(root, rural_only=False, mauville_only=False):
 # This tiny encoder avoids depending on the engine/runtime or a Lua binding.
 encoder=r'''local function j(v) if type(v)=='number'then return string.format('%.17g',v)elseif type(v)=='string'then return string.format('%q',v)elseif type(v)=='boolean'then return tostring(v)end local a={} if #v>0 then for _,x in ipairs(v)do a[#a+1]=j(x)end return '['..table.concat(a,',')..']'end for k,x in pairs(v)do a[#a+1]=j(tostring(k))..':'..j(x)end return '{'..table.concat(a,',')..'}'end io.write(j({data=dofile('lib/ImportedFenceData.lua'),families=dofile('lib/Gen3FenceFamilies.lua').ornate,rural=dofile('lib/Gen3FenceFamilies.lua').rural,mauville=dofile('lib/Gen3FenceFamilies.lua').mauville,mauvilleData=dofile('lib/ImportedMauvilleFencePrimitives.lua')}))'''
 source=json.loads(subprocess.check_output(['luajit','-e',encoder],cwd=root));models={};lookup={}
 for mid,segments in sorted(source['families'].items(),key=lambda p:int(p[0])):
  signature=tuple(tuple(s)for s in segments)
  if signature in lookup:models['oras_rustboro_joined_'+mid]=copy.deepcopy(models[lookup[signature]]);continue
  parts=[]
  for si,(length,x,z,rotation)in enumerate(segments):
   for original in source['data']['oras_rustboro_fence_'+str(length)]['parts']:
    p=copy.deepcopy(original);p['name']+='_'+str(si)
    for v in p['vertices']:
     vx,vz=v[0]-length/2,v[2]
     if rotation==1:vx,vz=-vz,vx
     v[0],v[2]=vx+x,vz+z
    parts.append(p)
  name='oras_rustboro_joined_'+mid
  models[name]=dict(parts=clean(parts),anchors={'center':[8,0,8]});lookup[signature]=name
  for p in models[name]['parts']:
   p['vertices']=[[round(value,7)+0.0 for value in v]for v in p['vertices']]
 if not rural_only and not mauville_only:write_models(root/'lib/ImportedFenceJoinedData.lua',models)
 rural={'oras_rural_joined_'+mid:rural_model(source['data']['oras_rural_fence'],profile)
        for mid,profile in sorted(source['rural'].items(),key=lambda p:int(p[0]))}
 if not mauville_only:write_models(root/'lib/ImportedRuralFenceData.lua',rural)
 models.update(rural)
 mauville={}
 for mid,segments in sorted(source['mauville'].items(),key=lambda p:int(p[0])):
  parts=[]
  for si,(length,x,z,rotation)in enumerate(segments):
   for original in source['mauvilleData']['oras_mauville_fence_'+str(length).replace('.','_')]['parts']:
    p=copy.deepcopy(original);p['name']+='_'+str(si)
    for v in p['vertices']:
     vx,vz=v[0]-length/2,v[2]
     if rotation==1:vx,vz=-vz,vx
     v[0],v[2]=vx+x,vz+z
    parts.append(p)
  mauville['oras_mauville_joined_'+mid]=dict(parts=clean(parts),anchors={'center':[8,0,8]})
 write_models(root/'lib/ImportedMauvilleFenceData.lua',mauville,12)
 models.update(mauville)
 return models

