#!/usr/bin/env python3
"""Regenerate data/gen3_rs_parity.lua from QA exports (identifiers only).

  gen3_rs_parity_table.py CANDIDATES.csv EMERALD_HASHES.tsv RUBY_HASHES.tsv OUT.lua

CANDIDATES.csv comes from tools/qa/gen3-rs-parity-candidates.lua; hashes from
tools/qa/gen3-metatile-hashes.lua. Hash-identical drawings are accepted;
differing drawings were reviewed on side-by-side source sheets and only the
REJECT entries below depict a different object. Update REJECT after any new
review; never approve a differing kind without inspecting it.
"""
import csv, sys, collections

REJECT = {('general__lilycove', '03E', 'tree'), ('general__mauville', '03E', 'tree'),
          ('general__mauville', '03F', 'tree'), ('general__meteor_falls', '202', 'steps')}
# Kinds whose differing RS drawings were inspected and depict the same object.
REVIEWED_DIFFERENT = {'cliff', 'tree', 'ledge', 'fence', 'grass'}

def hashes(p):
    return {(r['canonical'], r['mid']): r['hash'] for r in csv.DictReader(open(p), delimiter='\t')}

def main(cand, eh, rh, out):
    E, R = hashes(eh), hashes(rh)
    keep = collections.defaultdict(list)
    for r in csv.DictReader(open(cand)):
        k, pair, mid = r['emerald_kind'], r['pair'], r['mid']
        same = (pair, mid) in E and E.get((pair, mid)) == R.get((pair, mid))
        if k == 'flat' and (r['collision'] == 'blocked' or not same): continue
        if (pair, mid, k) in REJECT: continue
        if not same and k not in REVIEWED_DIFFERENT: continue
        keep[k].append((pair, mid, same))
    lines = ['-- Ruby/Sapphire metatiles approved to reuse the Emerald shape vocabulary.',
             '-- Generated by tools/qa/gen3_rs_parity_table.py from official Gen1Recomp',
             '-- 0.3.86 imports (gen3-rs-parity-candidates.lua + gen3-metatile-hashes.lua).',
             '-- Hash-identical composited 16x16 under+over drawings are accepted; differing',
             '-- cliff/tree/ledge/fence/grass drawings were inspected side by side and show',
             '-- the same object redrawn. Rejected: 03E/03F white rails (not trees) and the',
             '-- Meteor Falls 202 treads. Ruby and Sapphire candidates/hashes are identical.',
             '-- Key: primary__secondary:MID -> Emerald kind. Identifiers only; no pixels.',
             'return {']
    for k in sorted(keep):
        items = sorted(set(keep[k]))
        lines.append(f' -- {k}: {len(items)} ids ({sum(1 for i in items if i[2])} hash-identical)')
        ent = [f'["{p}:{m}"]="{k}"' for p, m, _ in items]
        for i in range(0, len(ent), 4): lines.append(' ' + ','.join(ent[i:i + 4]) + ',')
    lines.append('}')
    open(out, 'w').write('\n'.join(lines) + '\n')

if __name__ == '__main__':
    main(*sys.argv[1:5])
