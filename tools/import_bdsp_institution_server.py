#!/usr/bin/env python3
"""Select the original BDSP Galactic warehouse server; source archive stays local."""
import argparse,hashlib,io,json,zipfile
from pathlib import Path
from PIL import Image
from import_scenery_models import dae_static,safe_path
from import_oras_home_furniture import normalized,close_rims
from import_oras_grass import lua


def convert(archive,output):
    raw=archive.read_bytes()
    with zipfile.ZipFile(io.BytesIO(raw))as z:
        if len(z.infolist())>1000 or sum(i.file_size for i in z.infolist())>268435456:raise ValueError('source archive exceeds budget')
        for info in z.infolist():safe_path(info.filename)
        scene=z.read('1F.dae')
        if hashlib.sha256(scene).hexdigest()!='25d1957f0139cd0d4210f611693fdff506eb13035161e086316e3b62d75da001':raise ValueError('unreviewed source scene')
        selected=[p for p in dae_static(scene)if p['geometry']=='P_C_001_Server_01-mesh']
        if len(selected)!=1:raise ValueError('original server identity changed')
        source=selected[0]
        if source['texture']!='T_C_001_Server_01_C.png'or source['triangle_count']!=36 or source['skinned_bind_pose']:raise ValueError('source server material/topology changed')
        png=z.read(source['texture']);im=Image.open(io.BytesIO(png));rgba=im.convert('RGBA')
        if im.size!=(256,256)or set(rgba.tobytes()[3::4])!={255}:raise ValueError('unreviewed source server transparency')
    texture='assets/scenery/bdsp-institution-server/'+source['texture']
    part=dict(name='source_P_C_001_Server_01',texture=texture,material=source['texture'],
        vertices=[list(v)for v in source['vertices']],indices=list(range(1,len(source['vertices'])+1)),
        colors=[[1,1,1,1]]*len(source['vertices']),role='source_institution_server',alphaMode='cutout',opacity=1,
        wrapS=source['wrapS'],wrapT=source['wrapT'])
    model,meta=normalized([part])
    contact_count=0
    for v in part['vertices']:
        if abs(v[1])<1e-6:v[1]=0;contact_count+=1
    if contact_count!=18:raise ValueError('reviewed source underside contact stream changed')
    # Normalize tiny Collada meter/hierarchy coordinates before welding rims;
    # the single original six-edge underside stays on its original plane.
    model['parts'].extend(close_rims(part,[6],(4,100),texture_size=256))
    name='bdsp_galactic_server';folder=output/'assets/scenery/bdsp-institution-server';folder.mkdir(parents=True,exist_ok=True)
    (folder/source['texture']).write_bytes(png);(output/'lib').mkdir(parents=True,exist_ok=True)
    (output/'lib/ImportedInstitutionServerData.lua').write_text('-- Original BDSP Galactic warehouse server; generated by tools/import_bdsp_institution_server.py.\nreturn '+lua({name:model})+'\n')
    report=dict(source='User-supplied 361484.zip',game='Pokemon Brilliant Diamond / Shining Pearl',originalGameArt='Nintendo / Creatures / GAME FREAK / ILCA',
        archiveSha256=hashlib.sha256(raw).hexdigest(),scene='1F.dae',sceneSha256=hashlib.sha256(scene).hexdigest(),geometry=source['geometry'],texture=source['texture'],
        texturePngSha256=hashlib.sha256(png).hexdigest(),textureRgbaSha256=hashlib.sha256(rgba.tobytes()).hexdigest(),**meta,
        sourceTriangles=36,authoredClosureTriangles=6,sourceFront='+Z',contactPrecisionTolerance=1e-6,
        processing='Selected original static server only. Original Collada hierarchy/meter/Y-up transforms, positions, UVs and original PNG retained; uniformly normalized. Only original underside Y precision noise below 1e-6 normalized units snaps to the bottom plane; upper geometry stays exact. One authored underside cap follows the existing six-edge rim. RGB is white; no source shadow planes, floors, glow, lighting/effect textures or other room furniture. Native fits preserve source proportions and recess only Y0 contact vertices below unchanged native floors.')
    (folder/'provenance.json').write_text(json.dumps(report,indent=2)+'\n')
    return name,model


if __name__=='__main__':
    p=argparse.ArgumentParser(description=__doc__);p.add_argument('archive',type=Path);p.add_argument('output',type=Path);a=p.parse_args()
    name,m=convert(a.archive,a.output);print(name,len(m['parts']),sum(len(p['indices'])//3 for p in m['parts']))
